export type TleRecord = {
  norad: string;
  name: string;
  line1: string;
  line2: string;
  epochUtc: string;
};

function epochToUtc(epochField: string): string {
  const yy = Number(epochField.slice(0, 2));
  const year = yy < 57 ? 2000 + yy : 1900 + yy;
  const dayOfYear = Number(epochField.slice(2));
  const date = new Date(Date.UTC(year, 0, 1) + (dayOfYear - 1) * 86400000);
  return date.toISOString().replace("T", " ").slice(0, 19) + " UTC";
}

function tle(norad: string, name: string, line1: string, line2: string): TleRecord {
  return { norad, name, line1, line2, epochUtc: epochToUtc(line1.slice(18, 32)) };
}

