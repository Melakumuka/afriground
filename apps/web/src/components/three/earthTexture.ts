function lngLatToXY(lng: number, lat: number, W: number, H: number): [number, number] {
  const x = ((lng + 180) / 360) * W;
  const y = ((90 - lat) / 180) * H;
  return [x, y];
}

function drawRing(
  ctx: CanvasRenderingContext2D,
  poly: [number, number][],
  W: number,
  H: number,
  fill?: string,
  stroke?: string
) {
  ctx.beginPath();
  for (let i = 0; i < poly.length; i++) {
    const [x, y] = lngLatToXY(poly[i][0], poly[i][1], W, H);
    if (i === 0) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
  }
  ctx.closePath();
  if (fill) ctx.fill();
  if (stroke) ctx.stroke();
}

let cached: THREE.CanvasTexture | null = null;

export function createEarthTexture(): THREE.CanvasTexture {
  if (cached) return cached;
  const W = 2048;
  const H = 1024;
  const canvas = document.createElement("canvas");
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext("2d")!;

  // Ocean — deep graphite
  ctx.fillStyle = "#0D0E10";
  ctx.fillRect(0, 0, W, H);

  // Land — subtly lifted graphite with faint signal-orange edge
  drawRing(ctx, AFRICA_POLY, W, H, "#1E2126", "rgba(226,102,47,0.18)");

  // Graticule — faint engineering grid
  ctx.strokeStyle = "rgba(141,147,155,0.10)";
  ctx.lineWidth = 1;
  for (let lng = -180; lng <= 180; lng += 15) {
    ctx.beginPath();
    const x = ((lng + 180) / 360) * W;
    ctx.moveTo(x, 0);
    ctx.lineTo(x, H);
    ctx.stroke();
  }
  for (let lat = -75; lat <= 75; lat += 15) {
    ctx.beginPath();
    const y = ((90 - lat) / 180) * H;
    ctx.moveTo(0, y);
    ctx.lineTo(W, y);
    ctx.stroke();
  }

  // East Africa reach highlight (Entoto 9.076N 38.74E)
  const [hx, hy] = lngLatToXY(38.74, 9.076, W, H);
  const grad = ctx.createRadialGradient(hx, hy, 0, hx, hy, 140);
  grad.addColorStop(0, "rgba(226,102,47,0.22)");
  grad.addColorStop(1, "rgba(226,102,47,0)");
  ctx.fillStyle = grad;
  ctx.fillRect(hx - 140, hy - 140, 280, 280);

  const tex = new THREE.CanvasTexture(canvas);
  tex.colorSpace = THREE.SRGBColorSpace;
  tex.anisotropy = 8;
  cached = tex;
  return tex;
}
